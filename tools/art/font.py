# Lowercase accents replace the two empty rows above the letter.
LOWER_MARKS = {
    "á": ("a", "..#./.#.."),
    "é": ("e", "..#./.#.."),
    "ó": ("o", "..#./.#.."),
    "ú": ("u", "..#./.#.."),
    "ü": ("u", "#..#/...."),
    "ñ": ("n", ".#.#/#.#."),
}
# Capital accents go in the two rows above the letter body.
UPPER_MARKS = {
    "Á": ("A", "...#./..#.."),
    "É": ("E", "...#./..#.."),
    "Í": ("I", "..#/.#."),
    "Ó": ("O", "...#./..#.."),
    "Ú": ("U", "...#./..#.."),
    "Ü": ("U", ".#.#./....."),
    "Ñ": ("N", ".#.#./#.#.."),
}
MISSING_GLYPH = "#####/#...#/#...#/#...#/#...#/#...#/#####"


def _rows(glyph: str) -> list[str]:
    rows = glyph.split("/")
    if len({len(row) for row in rows}) != 1:
        raise ValueError(f"Glyph rows differ in width: {glyph}")
    return rows


def _cell_rows(char: str) -> list[str]:
    """Rows of a glyph placed in its cell, accent rows included."""
    if char in UPPER_MARKS:
        base, mark = UPPER_MARKS[char]
        return _rows(mark) + _rows(GLYPHS[base])
    if char in LOWER_MARKS:
        base, mark = LOWER_MARKS[char]
        body = _rows(mark) + _rows(GLYPHS[base])[ACCENT_ROWS:]
    else:
        body = _rows(GLYPHS[char])
    if len(body) not in (BODY_ROWS, CELL_SIZE[1] - ACCENT_ROWS):
        raise ValueError(f"Glyph {char!r} has {len(body)} rows")
    return ["." * len(body[0])] * ACCENT_ROWS + body


def _draw(sheet: pygame.Surface, index: int, rows: list[str]) -> None:
    if len(rows[0]) > CELL_SIZE[0] - 1 or len(rows) > CELL_SIZE[1]:
        raise ValueError(f"Glyph {index} does not fit its cell")
    left = index % SHEET_COLUMNS * CELL_SIZE[0]
    top = index // SHEET_COLUMNS * CELL_SIZE[1]
    for y, row in enumerate(rows):
        for x, char in enumerate(row):
            if char == INK:
                sheet.set_at((left + x, top + y), PALETTE[FONT_COLOR])


def build() -> dict[str, pygame.Surface]:
    sheet = pygame.Surface(SHEET_SIZE, pygame.SRCALPHA)
    for index, char in enumerate(FONT_CHARS):
        if char != " ":
            _draw(sheet, index, _cell_rows(char))
    _draw(sheet, len(FONT_CHARS), ["....."] * ACCENT_ROWS + _rows(MISSING_GLYPH))
    return {FONT_SHEET: sheet}
